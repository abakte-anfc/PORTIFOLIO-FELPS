import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser = await chromium.launch(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH, headless: true } : { channel: "chrome", headless: true });
await fs.mkdir('artifacts', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:5173');
  await page.locator('#about').scrollIntoViewIfNeeded();
  const card = page.locator('.ftp-photo');
  const normal = page.locator('.about-photo-normal');
  const hover = page.locator('.about-photo-3d');
  await page.waitForFunction(() => [...document.querySelectorAll('.ftp-photo-frame img')].every(image => image.complete && image.naturalWidth > 0));
  const initial = await card.boundingBox();
  assert.equal(await normal.evaluate(e => getComputedStyle(e).objectFit), 'cover');
  assert.equal(await normal.evaluate(e => getComputedStyle(e).opacity), '1');
  await page.screenshot({ path: 'artifacts/about-normal.png' });
  await card.hover({ position: { x: initial.width * .8, y: initial.height * .3 } });
  await page.waitForTimeout(600);
  assert.equal(await card.getAttribute('data-3d'), 'true');
  assert.equal(await hover.evaluate(e => getComputedStyle(e).opacity), '1');
  assert.notEqual(await page.locator('.ftp-photo>.ftp-folder').evaluate(e => getComputedStyle(e).transform), 'none');
  await page.screenshot({ path: 'artifacts/about-3d.png' });
  await page.mouse.move(10, 10);
  await page.waitForTimeout(600);
  assert.equal(await card.getAttribute('data-3d'), 'false');
  assert.equal(await normal.evaluate(e => getComputedStyle(e).opacity), '1');
  const final = await card.boundingBox();
  assert.ok(Math.abs(final.height - initial.height) < 1);
  await card.focus();
  assert.equal(await card.getAttribute('data-3d'), 'true');
  await page.close();
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  await mobile.goto('http://127.0.0.1:5173');
  await mobile.locator('#about').scrollIntoViewIfNeeded();
  await mobile.locator('.ftp-photo').focus();
  assert.equal(await mobile.locator('.ftp-photo').getAttribute('data-3d'), 'false');
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await mobile.screenshot({ path: 'artifacts/about-mobile.png' });
  assert.deepEqual(errors, []);
  console.log('Images load; 3D swap, return, stable sizing, keyboard and reduced motion: OK');
} finally { await browser.close(); }
